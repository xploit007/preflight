#!/usr/bin/env node
'use strict';

/**
 * Bundles scripts/scan.js and every module it requires (scripts/lib/, scripts/checks/) into
 * one self-contained file, skills/preflight/scripts/scan.js. `npx skills add` copies only the
 * skill folder, so the skill needs its own copy of the scanner; the plugin uses scripts/ directly.
 *
 *   node tools/build-skill.js          write the bundle
 *   node tools/build-skill.js --check  exit 1 if the bundle is out of date
 */

const fs = require('fs');
const path = require('path');
const { blankComments } = require('../scripts/lib/util');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'scripts');
const OUT = path.join(ROOT, 'skills', 'preflight', 'scripts', 'scan.js');

/** Every module reachable from scripts/scan.js through relative require() calls. */
function collect() {
  const modules = new Map();
  const visit = (abs) => {
    const id = path.relative(SRC, abs).split(path.sep).join('/');
    if (modules.has(id)) return;
    const source = fs.readFileSync(abs, 'utf8');
    modules.set(id, source);
    // Only real code: requires mentioned in comments or regex literals don't count.
    for (const m of blankComments(source, '.js').matchAll(/require\(\s*['"](\.{1,2}\/[^'"]+)['"]\s*\)/g)) {
      let target = path.resolve(path.dirname(abs), m[1]);
      if (!target.endsWith('.js')) target += '.js';
      visit(target);
    }
  };
  visit(path.join(SRC, 'scan.js'));
  return modules;
}

const RUNTIME = `
const __path = require('path');
const __cache = {};
function __require(from, request) {
  if (!request.startsWith('.')) return require(request);
  let id = __path.posix.normalize(__path.posix.join(__path.posix.dirname(from), request));
  if (!id.endsWith('.js')) id += '.js';
  if (__cache[id]) return __cache[id].exports;
  if (!__modules[id]) throw new Error('preflight bundle is missing module ' + id);
  const module = { exports: {} };
  __cache[id] = module;
  __modules[id].call(module.exports, module, module.exports, (r) => __require(id, r));
  return module.exports;
}

__require('scan.js', './scan.js').main(process.argv.slice(2));
`;

function build() {
  const modules = collect();
  const ids = [...modules.keys()].sort((a, b) => (a === 'scan.js' ? -1 : b === 'scan.js' ? 1 : a < b ? -1 : 1));
  const parts = [
    '#!/usr/bin/env node',
    '// GENERATED by tools/build-skill.js from scripts/. Do not edit: change scripts/ and run `npm run build`.',
    '// Single-file copy of the preflight scanner for standalone skill installs (npx skills add).',
    "'use strict';",
    '',
    'const __modules = {',
  ];
  for (const id of ids) {
    const source = modules.get(id).replace(/^#!.*\n/, '');
    parts.push(`// ── ${id} ${'─'.repeat(Math.max(4, 70 - id.length))}`);
    parts.push(`${JSON.stringify(id)}: function (module, exports, require) {`);
    parts.push(source.trimEnd());
    parts.push('},');
  }
  parts.push('};');
  return `${parts.join('\n')}\n${RUNTIME}`;
}

function main() {
  const check = process.argv.includes('--check');
  const next = build();
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (check) {
    if (current !== next) {
      console.error('skills/preflight/scripts/scan.js is out of date. Run `npm run build`.');
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, next);
  fs.chmodSync(OUT, 0o755);
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${collect().size} modules, ${(next.length / 1024).toFixed(0)} KB).`);
}

if (require.main === module) main();

module.exports = { build };

#!/usr/bin/env node
'use strict';

/**
 * Generates skills/preflight/references/checklist.md and the checklist table in
 * README.md from scripts/lib/catalog.js, so docs and scanner can't drift apart.
 *
 *   node tools/gen-docs.js          write both files
 *   node tools/gen-docs.js --check  exit 1 if either file is out of date
 */

const fs = require('fs');
const path = require('path');
const { GROUPS, CHECKS } = require('../scripts/lib/catalog');

const ROOT = path.resolve(__dirname, '..');
const CHECKLIST = path.join(ROOT, 'skills', 'preflight', 'references', 'checklist.md');
const README = path.join(ROOT, 'README.md');
const TABLE_START = '<!-- checklist:start (generated by tools/gen-docs.js, do not edit by hand) -->';
const TABLE_END = '<!-- checklist:end -->';

const MODE_LABEL = {
  auto: 'auto',
  'auto+agent': 'auto + agent',
  manual: 'manual',
};

function checklistMarkdown() {
  const out = [];
  out.push(`# preflight checklist (${CHECKS.length} checks)`);
  out.push('');
  out.push('<!-- Generated by tools/gen-docs.js from scripts/lib/catalog.js. Edit the catalog, then run `npm run build`. -->');
  out.push('');
  out.push('Every check below has a stable id. `scripts/scan.js` emits exactly one result per id:');
  out.push('');
  out.push('```json');
  out.push('{ "id": "SEC-01", "title": "…", "severity": "critical|high|medium|low", "status": "pass|fail|warn|manual", "evidence": ["file:line — note"], "fix": "…", "question": "… (warn/manual only)" }');
  out.push('```');
  out.push('');
  out.push('- **fail**: the script is confident. Report it. Re-verify only if the evidence looks wrong.');
  out.push('- **warn**: a heuristic hit. Read the code at each evidence location and confirm or dismiss it.');
  out.push('- **manual**: the script can\'t decide (dashboards, legal context, intent). Answer the `question` from the code, or hand it to the owner.');
  out.push('- **pass**: nothing found, or the check doesn\'t apply (evidence says which).');
  out.push('');
  out.push('Modes: **auto** means the script decides. **auto + agent** means the script flags candidates and the agent verifies them. **manual** means the script gathers context and the agent or a human decides.');
  out.push('');
  out.push('## Contents');
  out.push('');
  out.push('| Group | Checks |');
  out.push('| :- | :- |');
  for (const g of GROUPS) {
    const ids = CHECKS.filter((c) => c.group === g.key).map((c) => `[${c.id}](#${anchor(c)})`);
    out.push(`| ${g.name} | ${ids.join(', ')} |`);
  }
  for (const g of GROUPS) {
    const checks = CHECKS.filter((c) => c.group === g.key);
    out.push('');
    out.push(`## ${g.name}`);
    for (const c of checks) {
      out.push('');
      out.push(`### ${c.id}: ${c.title}`);
      out.push('');
      out.push(`**Severity:** ${c.severity} · **Mode:** ${MODE_LABEL[c.mode]} · **Script:** \`scripts/checks/${c.script}\``);
      out.push('');
      out.push(`- **What:** ${c.what}`);
      out.push(`- **Why it matters:** ${c.why}`);
      out.push(`- **How it's detected:** ${c.detect}`);
      out.push(`- **Fix:** ${c.fix}`);
      out.push(`- **Agent question (warn/manual):** ${c.question}`);
    }
  }
  out.push('');
  return out.join('\n');
}

/** GitHub-style heading anchor for "### SEC-01: Exposed database credentials". */
function anchor(c) {
  return `${c.id}: ${c.title}`
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .trim()
    .replace(/\s/g, '-');
}

function readmeTable() {
  const groupName = new Map(GROUPS.map((g) => [g.key, g.name]));
  const out = [TABLE_START, '', '| ID | Check | Group | Severity | Auto/manual |', '| :- | :- | :- | :- | :- |'];
  for (const c of CHECKS) {
    out.push(`| ${c.id} | ${c.title} | ${groupName.get(c.group)} | ${c.severity} | ${MODE_LABEL[c.mode]} |`);
  }
  out.push('', TABLE_END);
  return out.join('\n');
}

function updatedReadme(current) {
  const start = current.indexOf(TABLE_START);
  const end = current.indexOf(TABLE_END);
  if (start === -1 || end === -1 || end < start) return null;
  return current.slice(0, start) + readmeTable() + current.slice(end + TABLE_END.length);
}

function main() {
  const check = process.argv.includes('--check');
  const stale = [];

  const checklist = checklistMarkdown();
  const currentChecklist = fs.existsSync(CHECKLIST) ? fs.readFileSync(CHECKLIST, 'utf8') : '';
  if (currentChecklist !== checklist) {
    if (check) stale.push(path.relative(ROOT, CHECKLIST));
    else {
      fs.mkdirSync(path.dirname(CHECKLIST), { recursive: true });
      fs.writeFileSync(CHECKLIST, checklist);
    }
  }

  if (fs.existsSync(README)) {
    const current = fs.readFileSync(README, 'utf8');
    const next = updatedReadme(current);
    if (next === null) {
      console.error(`README.md is missing the ${TABLE_START} / ${TABLE_END} markers`);
      process.exitCode = 1;
    } else if (next !== current) {
      if (check) stale.push('README.md');
      else fs.writeFileSync(README, next);
    }
  }

  if (stale.length) {
    console.error(`Out of date: ${stale.join(', ')}. Run \`npm run build\`.`);
    process.exitCode = 1;
  } else if (!check) {
    console.log(`Wrote ${path.relative(ROOT, CHECKLIST)} (${CHECKS.length} checks)${fs.existsSync(README) ? ' and the README table' : ''}.`);
  }
}

if (require.main === module) main();

module.exports = { checklistMarkdown, readmeTable, anchor };
